export const statusBadgeVariant = (
  status: string,
): NonNullable<VariantProps<typeof badgeVariants>["variant"]> => {
  switch (status) {
    case "succeeded":
    case "active":
    case "ok":
      return "success";
    case "failed":
    case "error":
      return "destructive";
    case "filtered":
    case "paused":
    case "draft":
    case "ignored":
      return "muted";
    case "started":
    case "retrying":
    case "queued":
    case "running":
      return "warning";
    default:
      return "default";
  }
};